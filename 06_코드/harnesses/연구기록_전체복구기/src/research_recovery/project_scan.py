def _is_excluded(path: Path, root: Path) -> bool:
    try:
        parts = path.relative_to(root).parts
    except Exception:
        return False
    if any(part in DEFAULT_EXCLUDES for part in parts):
        return True
    if len(parts) >= 2 and parts[0] == "04_근거" and parts[1] == "복구증거":
        return True
    # Do not recursively hash the recovery output generated by this harness.
    rel = "/".join(parts)
    if rel in RECOVERY_GENERATED_PATHS:
        return True
    if rel.startswith("08_검증/reports/연구기록복구/"):
        return True
    if rel.startswith("99_보관/복구전_문서백업_"):
        return True
    if rel.startswith("04_근거/복구증거/원본보관/"):
        return True
    if rel in {
        "12_협업/역할목록.yaml",
        "12_협업/역할간_인계기록.jsonl",
        "12_협업/역할복구_렌더_보고서.json",
    }:
        return True
    if rel.startswith("12_협업/역할별_연구/") or rel.startswith("12_협업/역할간_입출력계약/"):
        return True
    return False


def scan_project(project_root: Path) -> dict[str, Any]:
    project_root = project_root.resolve()
    paths = Paths(project_root)
    rows: list[dict[str, Any]] = []
    for p in sorted(project_root.rglob("*"), key=lambda x: str(x).lower()):
        if not p.is_file() or _is_excluded(p, project_root):
            continue
        try:
            stat = p.stat()
            digest = sha256_file(p)
        except OSError as exc:
            rows.append({
                "path": safe_relpath(p, project_root),
                "status": "unreadable",
                "error": f"{type(exc).__name__}: {exc}",
            })
            continue
        rows.append({
            "path": safe_relpath(p, project_root),
            "absolute_path": str(p.resolve()),
            "sha256": digest,
            "size_bytes": stat.st_size,
            "modified_at": stat.st_mtime,
            "suffix": p.suffix.lower(),
            "status": "readable",
        })
    write_jsonl(paths.project_files, rows)

    git_rows: list[dict[str, Any]] = []
    git_report: dict[str, Any] = {"available": False}
    git_probe = run_command(["git", "rev-parse", "--show-toplevel"], cwd=project_root)
    if git_probe.returncode == 0:
        git_root = Path(git_probe.stdout.strip()).resolve()
        git_report["available"] = True
        git_report["git_root"] = str(git_root)
        head = run_command(["git", "rev-parse", "HEAD"], cwd=git_root)
        status = run_command(["git", "status", "--porcelain=v1"], cwd=git_root)
        log = run_command(
            ["git", "log", "--date=iso-strict", "--pretty=format:%H%x09%aI%x09%an%x09%s", "--name-status", "--find-renames"],
            cwd=git_root,
            timeout=120,
        )
        branches = run_command(["git", "branch", "--all", "--format=%(refname)%09%(objectname)%09%(upstream:short)"], cwd=git_root)
        reflog = run_command(["git", "reflog", "--date=iso-strict", "--format=%H%x09%gD%x09%gI%x09%gs"], cwd=git_root, timeout=120)
        stashes = run_command(["git", "stash", "list", "--date=iso-strict", "--format=%gd%x09%H%x09%ci%x09%s"], cwd=git_root)
        worktrees = run_command(["git", "worktree", "list", "--porcelain"], cwd=git_root)
        git_report.update({
            "head": head.stdout.strip() if head.returncode == 0 else None,
            "dirty": bool(status.stdout.strip()) if status.returncode == 0 else None,
            "status_output": status.stdout,
            "branches": branches.stdout.splitlines() if branches.returncode == 0 else [],
            "reflog": reflog.stdout.splitlines() if reflog.returncode == 0 else [],
            "stashes": stashes.stdout.splitlines() if stashes.returncode == 0 else [],
            "worktrees": worktrees.stdout.splitlines() if worktrees.returncode == 0 else [],
            "errors": [x for x in [head.stderr.strip(), status.stderr.strip(), log.stderr.strip(), branches.stderr.strip(), reflog.stderr.strip(), stashes.stderr.strip(), worktrees.stderr.strip()] if x],
        })
        current: dict[str, Any] | None = None
        for line in log.stdout.splitlines():
            if not line.strip():
                continue
            if "\t" in line and len(line.split("\t", 3)[0]) == 40:
                parts = line.split("\t", 3)
                current = {
                    "commit": parts[0],
                    "author_time": parts[1] if len(parts) > 1 else None,
                    "author": parts[2] if len(parts) > 2 else None,
                    "subject": parts[3] if len(parts) > 3 else None,
                    "changes": [],
                }
                git_rows.append(current)
            elif current is not None:
                cols = line.split("\t")
                current["changes"].append({"status": cols[0], "paths": cols[1:]})
    write_jsonl(paths.git_history, git_rows)
    json_dump(paths.recovery / "정규화기록" / "프로젝트스캔_보고서.json", {
        "generated_at": utc_now(),
        "project_root": str(project_root),
        "file_count": len(rows),
        "git": git_report,
        "git_commit_count": len(git_rows),
        "project_file_index": safe_relpath(paths.project_files, project_root),
        "git_history_index": safe_relpath(paths.git_history, project_root),
    })
    return {"file_count": len(rows), "git_commit_count": len(git_rows), "git": git_report}
